def build():
    out = []
    for div, (dname, kind, titles) in D.items():
        for i, t in enumerate(titles, 1):
            out.append((f"{div}{i:02d}", div, t, kind, f"{dname}: {t}",
                        f"Ты агент «{t}» (подразделение {dname}). Используй только официальные источники. Никогда не проси и не принимай "
                        f"seed-фразы, приватные ключи, предоплату. Результат передавай CEO с источником, условиями, сроком, наградой и затратами."))
    for code, t, kind in SERVICE:
        out.append((code, "S", t, kind, f"Служебный: {t}", f"Служебный агент «{t}». Следи за целостностью системы и сообщай CEO об отклонениях."))
    return out

def seed(c):
    for a in build():
        c.execute("INSERT OR IGNORE INTO agents(id,division,name,kind,role,instructions) VALUES(?,?,?,?,?,?)", a)
    c.commit()
    return c.execute("SELECT COUNT(*) FROM agents").fetchone()[0]

def pick(c, division, kind="discover"):
    """Наименее загруженный агент подразделения (по числу открытых задач)."""
    r = c.execute("""SELECT a.id FROM agents a LEFT JOIN tasks t ON t.agent_id=a.id AND t.status IN ('new','needs_owner')
                     WHERE a.active=1 AND a.division=? GROUP BY a.id ORDER BY COUNT(t.id), a.id LIMIT 1""", (division,)).fetchone()
    if not r:
        r = c.execute("SELECT id FROM agents WHERE active=1 AND kind=? LIMIT 1", (kind,)).fetchone()
    return r["id"] if r else None
